package com.barrapp

import androidx.test.core.app.ApplicationProvider
import com.barrapp.data.DayEntry
import com.barrapp.data.MovementDay
import com.barrapp.data.SkillGraph
import org.json.JSONArray
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config

/**
 * The skill path on the phone (docs/UX-PLAN.md B2).
 *
 * The states must be the ones barra/skills.py computes: the expected values in
 * src/test/resources/skills_state_cases.json were generated by Python
 * (skills.state / skills.next_up) for the muscle-up path. VERIFIED only from
 * barra's own measurements; doing a skill implies its prerequisites, as
 * CLAIMED, never VERIFIED.
 */
@RunWith(RobolectricTestRunner::class)
@Config(sdk = [34])
class SkillGraphTest {
    private val graph by lazy { SkillGraph.load(ApplicationProvider.getApplicationContext()) }

    @Test
    fun `the shipped graph loads with every skill`() {
        assertEquals(88, graph.size)
        assertEquals("Muscle-up", graph["muscle_up"]?.name)
        assertEquals("Dominada", graph["pull_up"]?.name)
    }

    @Test
    fun `states and the next step match barra's python`() {
        val text = javaClass.classLoader!!.getResource("skills_state_cases.json").readText()
        val cases = JSONArray(text)
        for (i in 0 until cases.length()) {
            val c = cases.getJSONObject(i)
            val verified = (0 until c.getJSONArray("verified").length())
                .map { c.getJSONArray("verified").getString(it) }.toSet()
            val target = c.getString("target")
            val st = graph.state(verified, emptySet())
            val expected = c.getJSONObject("states")
            val path = graph.path(target).map { it.id }.toSet()
            assertEquals(expected.keys().asSequence().toSet(), path)
            for (k in expected.keys()) assertEquals("$verified: $k", expected.getString(k), st[k])
            val next = if (c.isNull("next")) null else c.getString("next")
            assertEquals("$verified next", next, graph.nextOnPath(target, verified, emptySet())?.id)
        }
    }

    @Test
    fun `the path is ordered by tier, target last`() {
        val path = graph.path("muscle_up")
        assertEquals("muscle_up", path.last().id)
        assertTrue(path.zipWithNext().all { (a, b) -> a.tier <= b.tier })
    }

    @Test
    fun `an unknown target is an empty path`() {
        assertTrue(graph.path("not_a_skill").isEmpty())
    }

    private fun day(date: String, exercise: String, reps: Int, score: Int) = DayEntry(
        date = date, exercise = exercise, exerciseLabel = exercise, reps = reps, score = score,
        band = "solid", jobIds = emptyList(),
        byMovement = mapOf(exercise to MovementDay(exercise, exercise, reps, 1, score)),
    )

    @Test
    fun `verified means the skill's standard was met on enough days`() {
        val pu = graph["pull_up"]!!.standard!!
        val good = (1..pu.days).map { day("2026-10-0$it", "pull_up", pu.reps, pu.quality) }
        assertEquals(setOf("pull_up"), graph.verifiedFrom(good))
        val short = good.take(pu.days - 1)
        assertTrue(graph.verifiedFrom(short).isEmpty())
        val weak = good.map { day(it.date, "pull_up", pu.reps, pu.quality - 1) }
        assertTrue(graph.verifiedFrom(weak).isEmpty())
    }
}
